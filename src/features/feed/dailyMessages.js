/**
 * Índice estável por dia civil local (mesmo texto para todo o grupo no mesmo dia).
 */
export function getDailyMessage(date = new Date()) {
  const y = date.getFullYear();
  const m = date.getMonth() + 1;
  const d = date.getDate();
  const dayKey = y * 372 + m * 31 + d;
  const index = ((dayKey % DAILY_MESSAGES.length) + DAILY_MESSAGES.length) % DAILY_MESSAGES.length;
  return DAILY_MESSAGES[index];
}
